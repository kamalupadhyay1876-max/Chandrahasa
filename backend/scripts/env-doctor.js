'use strict';
const checks = [];
const add = (name, ok, note) => checks.push({name,ok,note});
const prod = process.env.NODE_ENV === 'production';
const secret = process.env.SECRET || '';
add('Node version >=18', Number(process.versions.node.split('.')[0]) >= 18, process.version);
add('SECRET configured', secret.length >= 32 && !/change-me|demo|replace/i.test(secret), secret ? `length ${secret.length}; value hidden` : 'not set; value hidden');
add('Production mode', prod, prod ? 'production' : 'development mode');
add('Razorpay key pair', Boolean(process.env.RAZORPAY_KEY_ID && process.env.RAZORPAY_KEY_SECRET), 'optional; online payments disabled until credentials are configured');
add('Razorpay webhook secret', Boolean(process.env.RAZORPAY_WEBHOOK_SECRET), 'optional but required for webhook event validation');
add('Razorpay Route activation', process.env.RAZORPAY_ROUTE_ENABLED === 'true', 'optional; keep disabled until Razorpay separately approves Route');
add('Seller KYC provider webhook secret', Boolean(process.env.SELLER_KYC_WEBHOOK_SECRET), 'optional; required for signed provider KYC/bank status callbacks');
add('Automatic seller payouts', process.env.AUTO_ROUTE_PAYOUTS === 'true', 'disabled by default; enable only after Route sandbox, KYC and finance sign-off');
add('Shiprocket credentials', Boolean(process.env.SHIPROCKET_EMAIL && process.env.SHIPROCKET_PASSWORD), 'optional; shipment creation disabled until configured');
add('Email service', Boolean(process.env.RESEND_API_KEY && process.env.MAIL_FROM), 'optional; configure before password-reset email delivery');
add('Persistent data path', Boolean(process.env.DATA_PATH), process.env.DATA_PATH ? 'path configured' : 'default local data directory; production deployment should use persistent storage');
for (const c of checks) console.log(`${c.ok?'PASS':'INFO'} ${c.name}: ${c.note}`);
const hardFail = checks.slice(0,2).some(c=>!c.ok);
console.log('\nThis diagnostic never prints credential values and does not verify provider connectivity.');
process.exitCode = hardFail ? 1 : 0;
